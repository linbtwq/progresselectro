const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const elements=new Map();
const el=id=>{if(!elements.has(id))elements.set(id,{classList:{add(){},remove(){},toggle(){}},focus(){},disabled:false});return elements.get(id)};
const ctx=vm.createContext({document:{getElementById:el,querySelector:el},fmt:String,shipmentItems:[],updateShipmentRow(){},updateShipmentSummary(){}});
vm.runInContext(fs.readFileSync('javascript/ui/quantityKeyboard.js','utf8'),ctx);
assert.equal(ctx.quantityKeyValue('12','3'), '123');
assert.equal(ctx.quantityKeyValue('12','3',true), '3');
assert.equal(ctx.quantityKeyValue('12','-'), '1');
assert.equal(ctx.quantityKeyValue('1','-'), '0');
assert.equal(ctx.quantityKeyValue('0','0'), '0');
assert.equal(ctx.quantityKeyValue('123456','7'), '123456');
assert.equal(ctx.quantityKeyValue('1','x'), '1');
vm.runInContext(`quantityDraft={item:{qty:0,maxQty:12,price:5},input:{value:0},row:{dataset:{idx:0}},value:'13',replace:false}`,ctx);
ctx.handleQuantityKey('OK');
assert.equal(vm.runInContext('quantityDraft.item.qty',ctx),0);
ctx.handleQuantityKey('-'); ctx.handleQuantityKey('2');
ctx.handleQuantityKey('OK');
assert.equal(vm.runInContext('quantityDraft',ctx),null);
vm.runInContext(`var item={qty:4,maxQty:12,price:5};quantityDraft={item,input:{},value:'9'}`,ctx);
ctx.closeQuantityKeyboard();
assert.equal(vm.runInContext('item.qty',ctx),4);
console.log('PASS: quantity replacement, digits, erase, length limit, stock validation, confirmation, cancel');
